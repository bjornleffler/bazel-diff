// files is a FileSource backed by a map.
type files map[string]string

// FileHash implements hasher.FileSource.
func (f files) FileHash(path string) (string, bool) {
	h, ok := f[path]
	return h, ok
}

// repos is a RepoSource backed by a map of repository identities.
type repos map[string]string

// RepoHash implements hasher.RepoSource.
func (r repos) RepoHash(name string) string { return r[name] }

// FileHash implements hasher.RepoSource; every repository here is fetched.
func (r repos) FileHash(name, path string) (string, bool) { return "", false }

// rule builds a rule target with a "srcs"-style attribute listing its inputs.
func rule(name, class string, inputs ...string) *buildpb.Target {
	return &buildpb.Target{
		Type: buildpb.Target_RULE.Enum(),
		Rule: &buildpb.Rule{
			Name:      proto.String(name),
			RuleClass: proto.String(class),
			Location:  proto.String("/abs/path/BUILD:10:5"),
			Attribute: []*buildpb.Attribute{
				{Name: proto.String("srcs"), Type: buildpb.Attribute_LABEL_LIST.Enum(), StringListValue: inputs},
				{Name: proto.String("generator_location"), Type: buildpb.Attribute_STRING.Enum(), StringValue: proto.String("pkg/BUILD:10:5")},
			},
			RuleInput: inputs,
		},
	}
}

// source builds a source file target.
func source(name string) *buildpb.Target {
	return &buildpb.Target{
		Type:       buildpb.Target_SOURCE_FILE.Enum(),
		SourceFile: &buildpb.SourceFile{Name: proto.String(name), Location: proto.String("/abs/path/BUILD:1:1")},
	}
}

// generated builds a generated file target.
func generated(name, rule string) *buildpb.Target {
	return &buildpb.Target{
		Type:          buildpb.Target_GENERATED_FILE.Enum(),
		GeneratedFile: &buildpb.GeneratedFile{Name: proto.String(name), GeneratingRule: proto.String(rule)},
	}
}

// graph returns a small workspace:
//
//	//app:bin -> //lib:lib -> //lib:lib.cc
//	         -> //gen:out (generated by //gen:gen -> @@dep+//:dep)
//	//other:other -> //other:other.cc
func graph() []*buildpb.Target {
	return []*buildpb.Target{
		rule("@@//app:bin", "cc_binary", "@@//lib:lib", "@@//gen:out"),
		rule("@@//lib:lib", "cc_library", "@@//lib:lib.cc"),
		source("@@//lib:lib.cc"),
		rule("@@//gen:gen", "genrule", "@@dep+//:dep"),
		generated("@@//gen:out", "@@//gen:gen"),
		rule("@@dep+//:dep", "filegroup", "@@dep+//:dep.txt"),
		source("@@dep+//:dep.txt"),
		rule("@@//other:other", "cc_library", "@@//other:other.cc"),
		source("@@//other:other.cc"),
	}
}

// hash runs the hasher and indexes the result by label.
func hash(t *testing.T, targets []*buildpb.Target, f files, r repos) map[string]snapshot.Target {
	t.Helper()
	out, err := hasher.Hash(targets, hasher.Options{Files: f, Repos: r, Workers: 2})
	if err != nil {
		t.Fatal(err)
	}
	m := make(map[string]snapshot.Target)
	for _, tgt := range out {
		m[tgt.Label] = tgt
	}
	return m
}

// baseline returns the file and repository state for graph().
func baseline() (files, repos) {
	return files{"lib/lib.cc": "aaa", "other/other.cc": "bbb"}, repos{"dep+": "v1"}
}

// changedLabels lists labels whose total hash differs.
func changedLabels(a, b map[string]snapshot.Target) map[string]bool {
	out := map[string]bool{}
	for l, t := range b {
		if a[l].Hash != t.Hash {
			out[l] = true
		}
	}
	return out
}

// expect checks that exactly the given labels changed.
func expect(t *testing.T, got map[string]bool, want ...string) {
	t.Helper()
	if len(got) != len(want) {
		t.Errorf("changed = %v, want %v", got, want)
		return
	}
	for _, w := range want {
		if !got[w] {
			t.Errorf("changed = %v, want %v", got, want)
			return
		}
	}
}

// TestDeterministic hashes the same input twice, in different orders.
func TestDeterministic(t *testing.T) {
	f, r := baseline()
	a := hash(t, graph(), f, r)
	reversed := graph()
	for i, j := 0, len(reversed)-1; i < j; i, j = i+1, j-1 {
		reversed[i], reversed[j] = reversed[j], reversed[i]
	}
	expect(t, changedLabels(a, hash(t, reversed, f, r)))
	if a["//app:bin"].Kind != "cc_binary" || a["//lib:lib.cc"].Kind != snapshot.KindSourceFile {
		t.Errorf("kinds wrong: %+v", a)
	}
}

// TestSourceChangePropagates edits one file and expects its reverse
// dependencies, and nothing else, to change.
func TestSourceChangePropagates(t *testing.T) {
	f, r := baseline()
	before := hash(t, graph(), f, r)
	f["lib/lib.cc"] = "changed"
	after := hash(t, graph(), f, r)
	expect(t, changedLabels(before, after), "//lib:lib.cc", "//lib:lib", "//app:bin")
	if before["//lib:lib"].Self != after["//lib:lib"].Self {
		t.Error("lib's Self changed although only its dependency did")
	}
	if before["//lib:lib.cc"].Self == after["//lib:lib.cc"].Self {
		t.Error("the file's Self did not change")
	}
}

// TestExternalRepoChange bumps an external repository's identity.
func TestExternalRepoChange(t *testing.T) {
	f, r := baseline()
	before := hash(t, graph(), f, r)
	r["dep+"] = "v2"
	after := hash(t, graph(), f, r)
	expect(t, changedLabels(before, after),
		"@@dep+//:dep", "@@dep+//:dep.txt", "//gen:gen", "//gen:out", "//app:bin")
}

// TestLocationIgnored moves a rule within its BUILD file.
func TestLocationIgnored(t *testing.T) {
	f, r := baseline()
	before := hash(t, graph(), f, r)
	moved := graph()
	moved[1].Rule.Location = proto.String("/elsewhere/BUILD:99:1")
	moved[1].Rule.Attribute[1].StringValue = proto.String("lib/BUILD:99:1")
	moved[2].SourceFile.Location = proto.String("/elsewhere/BUILD:1:1")
	expect(t, changedLabels(before, hash(t, moved, f, r)))
}

// TestAttributeChange edits a rule attribute.
func TestAttributeChange(t *testing.T) {
	f, r := baseline()
	before := hash(t, graph(), f, r)
	edited := graph()
	edited[7].Rule.Attribute = append(edited[7].Rule.Attribute, &buildpb.Attribute{
		Name: proto.String("copts"), Type: buildpb.Attribute_STRING_LIST.Enum(), StringListValue: []string{"-O2"},
	})
	expect(t, changedLabels(before, hash(t, edited, f, r)), "//other:other")
}

// TestStarlarkEnvironmentChange changes the rule class's .bzl environment.
func TestStarlarkEnvironmentChange(t *testing.T) {
	f, r := baseline()
	before := hash(t, graph(), f, r)
	edited := graph()
	edited[1].Rule.SkylarkEnvironmentHashCode = proto.String("new-bzl")
	expect(t, changedLabels(before, hash(t, edited, f, r)), "//lib:lib", "//app:bin")
}

// TestMissingFile treats a file that later appears as a change.
func TestMissingFile(t *testing.T) {
	f, r := baseline()
	delete(f, "other/other.cc")
	before := hash(t, graph(), f, r)
	f["other/other.cc"] = "new"
	expect(t, changedLabels(before, hash(t, graph(), f, r)), "//other:other.cc", "//other:other")
}

// TestTagsAndDeps checks the recorded tags and dependency indices.
func TestTagsAndDeps(t *testing.T) {
	targets := graph()
	targets[0].Rule.Attribute = append(targets[0].Rule.Attribute, &buildpb.Attribute{
		Name: proto.String("tags"), Type: buildpb.Attribute_STRING_LIST.Enum(), StringListValue: []string{"manual"},
	})
	f, r := baseline()
	out, err := hasher.Hash(targets, hasher.Options{Files: f, Repos: r})
	if err != nil {
		t.Fatal(err)
	}
	for _, tgt := range out {
		if tgt.Label != "//app:bin" {
			continue
		}
		if len(tgt.Tags) != 1 || tgt.Tags[0] != "manual" {
			t.Errorf("tags = %v", tgt.Tags)
		}
		var deps []string
		for _, d := range tgt.Deps {
			deps = append(deps, out[d].Label)
		}
		if len(deps) != 2 || deps[0] != "//lib:lib" || deps[1] != "//gen:out" {
			t.Errorf("deps = %v", deps)
		}
	}
}

// TestCycle makes sure a dependency cycle terminates.
func TestCycle(t *testing.T) {
	targets := []*buildpb.Target{
		rule("@@//a:a", "x", "@@//b:b"),
		rule("@@//b:b", "x", "@@//a:a"),
	}
	if _, err := hasher.Hash(targets, hasher.Options{}); err != nil {
		t.Fatal(err)
	}
}
